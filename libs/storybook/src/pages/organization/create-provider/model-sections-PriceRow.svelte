<script lang="ts">
  import { ModelCatalogPriceInputConstraints } from '@compallm/contract/validation'

  import { TextField } from '../../../components/fields'
  import { Checkbox } from '../../../components/selection'

  import { FieldHelp } from '../../../components/feedback'
  import { FormError } from '../../../components/form'
  import { priceEnabledFields, type ModelPriceField } from './model-options'

  import { readStore, fieldState } from '../../page-state.svelte'
  import { getCreateProviderController } from '../../../context'
  import { PriceComparison } from './model-sections'

  import ContentValue from '../../../components/Content.svelte'

  let {
    label,
    name,
  }: {
    label: string
    name: ModelPriceField
  } = $props()
  const __provider = getCreateProviderController()
  const id = $props.id()
  const enabled = fieldState<boolean>(() => `modelDraft.${priceEnabledFields[name]}`)!
  let catalogLabel = $derived(
    readStore(
      __provider.store,
      (s) => s.modelDraft?.catalogPriceLabels?.[(['inputPrice', 'outputPrice', 'cachedPrice'] as const).indexOf(name)],
      ['modelDraft.catalogPriceLabels'],
    ),
  )
  let template = $derived(
    readStore(__provider.store, (state) => state.modelDraft?.catalogPrices?.[name], ['modelDraft.catalogPrices']),
  )
  let help = $derived(
    {
      inputPrice: `
The rate for new input tokens that are not billed as cache reads. Enter US dollars per one million tokens.
Enable to override the template; uncheck to use its rate. Zero is an explicit free rate.
`,
      cachedPrice: `
The rate for input tokens that the provider reports as served from its prompt cache. A cheaper rate does not
enable caching by itself. Uncheck to use the template rate; unknown or unsupported is not the same as $0.
`,
      outputPrice: `
The rate for tokens generated by the model. Provider billing may also include reasoning tokens. This rate is
independent of the input price. Uncheck to use the template rate.
`,
    }[name],
  )
</script>

<div class="grid min-h-8 min-w-0 grid-cols-[minmax(0,1fr)_10.125rem] items-center gap-3">
  <div class="flex min-w-0 items-center gap-3">
    <div class="flex min-w-0 items-center gap-0.5">
      <label for={id} class="flex min-w-0 cursor-pointer items-center gap-1.5 text-xs sm:gap-2 sm:text-xsm">
        <Checkbox {id} size="compact" name={`modelDraft.${priceEnabledFields[name]}`}></Checkbox><span class="truncate">
          <ContentValue value={label} />
        </span>
      </label><FieldHelp label={`About ${label.toLowerCase()} pricing`}>{help}</FieldHelp>
    </div>
    <PriceComparison {name}></PriceComparison>
  </div>
  <div class="relative min-w-0" data-form-field={`modelDraft.${name}`}>
    {#if enabled.value !== false}<span
        aria-hidden="true"
        class="pointer-events-none absolute inset-y-0 left-2 z-1 flex items-center text-xsm text-muted-foreground"
      >
        $
      </span><TextField
        name={`modelDraft.${name}`}
        aria-label={`${label} price`}
        inputmode="decimal"
        min={ModelCatalogPriceInputConstraints.value.minimum}
        max={ModelCatalogPriceInputConstraints.value.maximum}
        required
        placeholder="Enter rate"
        class="rounded-lg pl-6.5 text-right"
      ></TextField>{:else}<span
        class="flex h-8 items-center justify-end text-xs text-muted-foreground"
        title={template === undefined || template === '' ? 'No template rate is available.' : `$${template} per 1M tokens`}
      >
        {#if template === undefined || template === ''}{catalogLabel ?? 'Not set'}{:else}Provider default{/if}
      </span>{/if}<FormError name={`modelDraft.${name}`}></FormError>
  </div>
</div>
