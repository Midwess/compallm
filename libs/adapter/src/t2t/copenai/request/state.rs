/// Protocol positions in compatible Chat JSON.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CompatibleOpenAIDecoderState {
    Request,
    Model,
    Stream,
    StreamOptions,
    StreamOptionsIncludeUsage,
    MaxCompletionTokens,
    TopP,
    TopK,
    Stop,
    StopSequence,
    ParallelToolCalls,

    Messages,
    Message,
    MessageRole,
    MessageContent,
    ContentPart,
    ContentPartType,
    ContentPartText,
    /// messages[].tool_call_id; a tool result is an ordinary tool-role message.
    MessageToolCallId,

    Tools,
    Tool,
    ToolType,
    ToolCalls,
    ToolCall,
    ToolCallId,
    ToolCallType,
    /// The nested function object in a tool, tool call, or named tool choice.
    Function,
    FunctionName,
    FunctionDescription,
    FunctionParameters,
    FunctionStrict,
    /// String-valued JSON arguments, not a nested JSON object on the wire.
    FunctionArguments,
    ToolChoice,
    ToolChoiceType,

    /// Assistant history fields, not root-level reasoning generation controls.
    MessageReasoning,
    ReasoningDetails,
    ReasoningDetail,
    ReasoningDetailType,
    ReasoningDetailId,
    ReasoningDetailFormat,
    ReasoningDetailIndex,
    ReasoningDetailSummary,
    ReasoningDetailText,
    ReasoningDetailData,
    ReasoningDetailSignature,

    ResponseFormat,
    ResponseFormatType,
    ResponseFormatJsonSchema,
    ResponseFormatJsonSchemaName,
    ResponseFormatJsonSchemaDescription,
    ResponseFormatJsonSchemaStrict,
    ResponseFormatJsonSchemaSchema,
    Provider,
    ProviderRequireParameters,
}
