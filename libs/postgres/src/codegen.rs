use anyhow::{Context, Result, bail};
use heck::ToUpperCamelCase;
use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::Path,
};

/// Generate public schema names without changing SeaORM's model declarations.
pub struct SchemaAliases;

impl SchemaAliases {
    pub fn render(schema_dir: &Path) -> Result<String> {
        let modules = fs::read_to_string(schema_dir.join("mod.rs"))
            .context("failed to read the generated schema module")?;
        let modules = syn::parse_file(&modules)?;
        let mut aliases = BTreeMap::new();
        let mut private_modules = BTreeSet::new();
        for item in modules.items {
            let syn::Item::Mod(module) = item else {
                continue;
            };
            if module.content.is_some() {
                continue;
            }
            let name = module.ident.to_string();
            // SeaORM's prelude exposes its original entity names. Leave it out
            // of the public facade and keep only the model modules it refers to.
            if name == "prelude" {
                continue;
            }
            private_modules.insert(name.clone());
            let filename = name.strip_prefix("r#").unwrap_or(&name);
            let model = fs::read_to_string(schema_dir.join(format!("{filename}.rs")))
                .with_context(|| format!("failed to read schema module {name}"))?;
            let has_model = syn::parse_file(&model)?
                .items
                .iter()
                .any(|item| matches!(item, syn::Item::Struct(model) if model.ident == "Model"));
            // Prelude and active-enum modules have no database Model.
            if !has_model {
                continue;
            }
            let singular = pluralizer::pluralize(filename, 1, false);
            let alias = format!("{}Schema", singular.to_upper_camel_case());
            syn::parse_str::<syn::Ident>(&alias).context("invalid generated schema alias")?;
            if let Some(previous) = aliases.insert(alias.clone(), name.clone()) {
                bail!("schema alias {alias} is ambiguous between {previous} and {name}");
            }
        }
        let mut output =
            String::from("// @generated by compallm-postgres generate-entity. Do not edit.\n\n");
        for module in &private_modules {
            output.push_str(&format!("mod {module};\n"));
        }
        output.push('\n');
        for (alias, module) in aliases {
            output.push_str(&format!("pub use self::{module}::Model as {alias};\n"));
        }
        // Public model fields may reference generated database enum types.
        if private_modules.contains("sea_orm_active_enums") {
            output.push_str("pub use self::sea_orm_active_enums::*;\n");
        }
        Ok(output)
    }

    pub fn generate(schema_dir: &Path) -> Result<()> {
        let aliases = Self::render(schema_dir)?;
        fs::write(schema_dir.join("mod.rs"), aliases)
            .context("failed to write generated schema module")
    }
}
