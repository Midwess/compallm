use sea_orm_migration::{
    prelude::*,
    sea_query::{IndexCreateStatement, TableCreateStatement},
};

#[derive(DeriveMigrationName)]
pub struct Migration;

#[async_trait::async_trait]
impl MigrationTrait for Migration {
    async fn up(&self, manager: &SchemaManager) -> Result<(), DbErr> {
        manager.create_table(users_table()).await?;
        manager.create_index(email_index()).await
    }

    async fn down(&self, manager: &SchemaManager) -> Result<(), DbErr> {
        // PostgreSQL removes the table's indexes and constraints with the table.
        manager
            .drop_table(Table::drop().table(Users::Table).to_owned())
            .await
    }
}

fn users_table() -> TableCreateStatement {
    Table::create()
        .table(Users::Table)
        // IDs are generated by Hero in the application, never by a DB sequence.
        .col(
            ColumnDef::new(Users::Id)
                .big_integer()
                .not_null()
                .primary_key(),
        )
        .col(ColumnDef::new(Users::Email).text().not_null())
        .col(ColumnDef::new(Users::DisplayName).text().not_null())
        .col(
            ColumnDef::new(Users::Status)
                .text()
                .not_null()
                .default("active"),
        )
        // A user is created only after successful email-code verification.
        .col(
            ColumnDef::new(Users::EmailVerifiedAt)
                .timestamp_with_time_zone()
                .not_null(),
        )
        .col(
            ColumnDef::new(Users::LastLoginAt)
                .timestamp_with_time_zone()
                .null(),
        )
        .col(
            ColumnDef::new(Users::CreatedAt)
                .timestamp_with_time_zone()
                .not_null()
                .default(Expr::current_timestamp()),
        )
        .col(
            ColumnDef::new(Users::UpdatedAt)
                .timestamp_with_time_zone()
                .not_null()
                .default(Expr::current_timestamp()),
        )
        .check(Expr::col(Users::Id).gt(0))
        .check(Expr::col(Users::Email).ne(""))
        .check(Expr::col(Users::Status).is_in(["active", "disabled"]))
        .to_owned()
}

fn email_index() -> IndexCreateStatement {
    Index::create()
        .name("users_email_unique")
        .table(Users::Table)
        .col(Func::lower(Expr::col(Users::Email)))
        .unique()
        .to_owned()
}

#[derive(DeriveIden)]
enum Users {
    Table,
    Id,
    Email,
    DisplayName,
    Status,
    EmailVerifiedAt,
    LastLoginAt,
    CreatedAt,
    UpdatedAt,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn postgres_schema_uses_application_ids_and_verified_passwordless_identity() {
        let sql = users_table().to_string(PostgresQueryBuilder);
        assert!(sql.contains(r#""id" bigint NOT NULL PRIMARY KEY"#));
        assert!(sql.contains(r#""display_name" text NOT NULL"#));
        assert!(!sql.to_lowercase().contains("serial"));
        assert!(!sql.to_lowercase().contains("password"));
        assert!(sql.contains(r#""email_verified_at" timestamp with time zone NOT NULL"#));
        assert!(sql.contains(r#"CHECK ("id" > 0)"#));
        assert!(sql.contains(r#"CHECK ("status" IN ('active', 'disabled'))"#));
    }

    #[test]
    fn email_is_unique_ignoring_case() {
        assert_eq!(
            email_index().to_string(PostgresQueryBuilder),
            r#"CREATE UNIQUE INDEX "users_email_unique" ON "users" ((LOWER("email")))"#,
        );
    }
}
