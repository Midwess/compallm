use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::Path,
};

use anyhow::{Context, Result, bail, ensure};
use serde_json::Value;

const MARKER: &str = "<!-- Generated by compallm-api; do not edit. -->";
const METHODS: &[&str] = &[
    "get", "put", "post", "delete", "options", "head", "patch", "trace",
];

/// Renders the exported contract without booting Loco or connecting to a database.
pub(crate) struct ApiDocumentation<'a> {
    document: &'a Value,
}

impl<'a> ApiDocumentation<'a> {
    pub(crate) fn new(document: &'a Value) -> Self {
        Self { document }
    }

    pub(crate) fn generate(&self, output: &Path) -> Result<usize> {
        let pages = self.render()?;
        let mut existing = Vec::new();
        Self::collect_files(output, &mut existing)?;
        // Validate ownership of every destination before changing any file.
        for relative in pages.keys() {
            let target = output.join(relative);
            if target.exists() {
                ensure!(
                    Self::is_generated(&fs::read_to_string(&target)?),
                    "refusing to overwrite handwritten documentation: {}",
                    target.display()
                );
            }
        }
        for (relative, content) in &pages {
            let target = output.join(relative);
            fs::create_dir_all(target.parent().context("missing output parent")?)?;
            fs::write(&target, content)?;
        }
        for path in existing {
            let relative = path
                .strip_prefix(output)?
                .to_string_lossy()
                .replace('\\', "/");
            if path.extension().is_some_and(|extension| extension == "md")
                && !pages.contains_key(&relative)
                && Self::is_generated(&fs::read_to_string(&path)?)
            {
                fs::remove_file(path)?;
            }
        }
        Ok(pages.len())
    }

    pub(crate) fn render(&self) -> Result<BTreeMap<String, String>> {
        let mut pages = BTreeMap::new();
        let mut destinations = BTreeSet::new();
        let mut links = Vec::new();
        let mut any_available = false;
        if let Some(paths) = self.document["paths"].as_object() {
            for (route, item) in paths {
                let item = self.resolve(item)?;
                for method in METHODS {
                    let Some(operation) = item.get(*method) else {
                        continue;
                    };
                    let path = Self::page_path(route, method)?;
                    ensure!(
                        destinations.insert(path.to_ascii_lowercase()),
                        "multiple operations map to {path}"
                    );
                    let title = Self::text(operation, "summary");
                    let label = format!("{} {route}", method.to_uppercase());
                    let available = operation["x-docs-available"].as_bool() == Some(true);
                    any_available |= available;
                    links.push(format!("- [{label}]({path}) — {title}"));
                    pages.insert(path, self.operation(route, method, item, operation)?);
                }
            }
        }
        let mut index = Self::header("API reference", any_available);
        index.push_str("# API reference\n\nUse the API on the same origin as your Compallm application. Paths below include the `/api` prefix. In examples, replace `https://compallm.example` with your deployment's origin.\n\n## Authentication\n\nCheck each operation's authentication section before calling it. Public operations do not require a user credential. Verification challenges are only for email confirmation, not access to protected resources.\n\n## Requests and errors\n\nSend the content type specified by the operation. Use the HTTP response status to distinguish success from failure; response schemas and recovery guidance are documented per status. JSON error responses, when declared, contain a human-readable `message`.\n\nExamples contain synthetic values. Replace challenges and credentials with values obtained from your own requests; do not publish real credentials.\n\n## Operations\n\n");
        index.push_str(&links.join("\n"));
        index.push('\n');
        pages.insert("index.md".into(), index);
        Ok(pages)
    }

    fn operation(
        &self,
        route: &str,
        method: &str,
        item: &Value,
        operation: &Value,
    ) -> Result<String> {
        let title = format!("{} {route}", method.to_uppercase());
        let mut page = Self::header(&title, operation["x-docs-available"] == true);
        page.push_str(&format!("# {title}\n\n"));
        for key in ["summary", "description"] {
            if let Some(text) = operation[key].as_str() {
                page.push_str(text);
                page.push_str("\n\n");
            }
        }
        page.push_str("## Authentication\n\n");
        let security = operation
            .get("security")
            .or_else(|| self.document.get("security"));
        match security
            .and_then(Value::as_array)
            .filter(|values| !values.is_empty())
        {
            None => page.push_str("Public endpoint. No user access credential is required.\n\n"),
            Some(requirements) => {
                page.push_str("Satisfy one of these alternatives (schemes within one alternative are all required):\n\n");
                for requirement in requirements {
                    if requirement
                        .as_object()
                        .is_some_and(|object| object.is_empty())
                    {
                        page.push_str("- Anonymous access is also allowed.\n");
                    } else {
                        page.push_str(&format!("- `{requirement}`\n"));
                        if let Some(schemes) = requirement.as_object() {
                            for name in schemes.keys() {
                                let scheme = self.resolve(
                                    &self.document["components"]["securitySchemes"][name],
                                )?;
                                ensure!(
                                    !scheme.is_null(),
                                    "missing OpenAPI security scheme {name}"
                                );
                                page.push_str(&format!(
                                    "\n{}\n\n```json\n{}\n```\n",
                                    Self::text(scheme, "description"),
                                    serde_json::to_string_pretty(scheme)?
                                ));
                            }
                        }
                    }
                }
                page.push('\n');
            }
        }
        let mut parameters = BTreeMap::new();
        for source in [item, operation] {
            for parameter in source["parameters"].as_array().into_iter().flatten() {
                let parameter = self.resolve(parameter)?;
                parameters.insert(
                    (Self::text(parameter, "in"), Self::text(parameter, "name")),
                    parameter,
                );
            }
        }
        if !parameters.is_empty() {
            page.push_str("## Parameters\n\n| Name | Location | Required | Description |\n| --- | --- | --- | --- |\n");
            for ((location, name), parameter) in &parameters {
                page.push_str(&format!(
                    "| {} | {} | {} | {} |\n",
                    Self::cell(name),
                    Self::cell(location),
                    parameter["required"] == true || *location == "path",
                    Self::cell(Self::text(parameter, "description"))
                ));
            }
            page.push('\n');
            for ((_, name), parameter) in parameters {
                page.push_str(&format!(
                    "### Parameter: {name}\n\n```json\n{}\n```\n\n",
                    serde_json::to_string_pretty(parameter)?
                ));
            }
        }
        if let Some(body) = operation.get("requestBody") {
            let body = self.resolve(body)?;
            page.push_str(&format!(
                "## Request body\n\nRequired: **{}**.\n\n{}",
                body["required"] == true,
                body["description"]
                    .as_str()
                    .map(|text| format!("{text}\n\n"))
                    .unwrap_or_default()
            ));
            self.content(&mut page, &body["content"])?;
            if let Some(media) = body["content"].get("application/json")
                && let Some(example) = self.media_example(media)?
            {
                let payload = serde_json::to_string_pretty(&example)?;
                let curl = format!(
                    "curl --request {} \\\n  'https://compallm.example{route}' \\\n  --header 'Content-Type: application/json' \\\n  --data {}",
                    method.to_uppercase(),
                    Self::shell_quote(&payload)
                );
                page.push_str(&format!("### Example request\n\n```bash\n{curl}\n```\n\n"));
            }
        } else {
            page.push_str(&format!("## Example request\n\n```bash\ncurl --request {} 'https://compallm.example{route}'\n```\n\n", method.to_uppercase()));
        }
        page.push_str("Replace URL parameters and supply any required query values and authentication described above.\n\n");
        page.push_str("## Responses\n\n");
        if let Some(responses) = operation["responses"].as_object() {
            for (status, response) in responses {
                let response = self.resolve(response)?;
                page.push_str(&format!(
                    "### {status}\n\n{}\n\n",
                    Self::text(response, "description")
                ));
                self.content(&mut page, &response["content"])?;
                if let Some(headers) = response["headers"].as_object() {
                    page.push_str("#### Response headers\n\n");
                    page.push_str(&format!(
                        "```json\n{}\n```\n\n",
                        serde_json::to_string_pretty(headers)?
                    ));
                }
            }
        }
        let depth = Self::page_path(route, method)?.split('/').count() - 1;
        let root = "../".repeat(depth);
        page.push_str(&format!(
            "## Related operations\n\nSee the [API reference]({root}index.md) for all operations.\n"
        ));
        Ok(page)
    }

    fn content(&self, page: &mut String, content: &Value) -> Result<()> {
        if let Some(types) = content.as_object() {
            for (mime, media) in types {
                page.push_str(&format!("Content type: `{mime}`.\n\n"));
                if let Some(schema) = media.get("schema") {
                    let schema = self.resolve(schema)?;
                    if !Self::text(schema, "description").is_empty() {
                        page.push_str(Self::text(schema, "description"));
                        page.push_str("\n\n");
                    }
                    if let Some(properties) = schema["properties"].as_object() {
                        page.push_str("| Field | Type | Required | Description |\n| --- | --- | --- | --- |\n");
                        for (name, property) in properties {
                            let property = self.resolve(property)?;
                            let required = schema["required"]
                                .as_array()
                                .is_some_and(|values| values.iter().any(|value| value == name));
                            let kind = property
                                .get("type")
                                .map(|value| {
                                    value
                                        .as_str()
                                        .map(str::to_owned)
                                        .unwrap_or_else(|| value.to_string())
                                })
                                .unwrap_or_else(|| "schema".into());
                            page.push_str(&format!(
                                "| {} | {} | {} | {} |\n",
                                Self::cell(name),
                                Self::cell(&kind),
                                required,
                                Self::cell(Self::text(property, "description"))
                            ));
                        }
                        page.push('\n');
                    }
                    page.push_str(&format!(
                        "<details>\n<summary>JSON schema</summary>\n\n```json\n{}\n```\n\n</details>\n\n",
                        serde_json::to_string_pretty(&self.expand(schema, 0)?)?
                    ));
                }
                if let Some(example) = self.media_example(media)? {
                    page.push_str(&format!(
                        "Example (synthetic values):\n\n```json\n{}\n```\n\n",
                        serde_json::to_string_pretty(&example)?
                    ));
                }
            }
        }
        Ok(())
    }

    fn media_example(&self, media: &Value) -> Result<Option<Value>> {
        if let Some(example) = media.get("example") {
            return Ok(Some(example.clone()));
        }
        if let Some(examples) = media["examples"].as_object() {
            for example in examples.values() {
                if let Some(value) = self.resolve(example)?.get("value") {
                    return Ok(Some(value.clone()));
                }
            }
        }
        self.example(&media["schema"], 0)
    }

    fn example(&self, schema: &Value, depth: usize) -> Result<Option<Value>> {
        if depth > 8 {
            return Ok(None);
        }
        let schema = self.resolve(schema)?;
        if let Some(value) = schema
            .get("example")
            .or_else(|| schema["examples"].get(0))
            .or_else(|| schema.get("default"))
            .or_else(|| schema["enum"].get(0))
        {
            return Ok(Some(value.clone()));
        }
        if let Some(properties) = schema["properties"].as_object() {
            let mut fields = serde_json::Map::new();
            for (name, property) in properties {
                if let Some(example) = self.example(property, depth + 1)? {
                    fields.insert(name.clone(), example);
                } else if schema["required"]
                    .as_array()
                    .is_some_and(|required| required.iter().any(|value| value == name))
                {
                    return Ok(None);
                }
            }
            return Ok(Some(Value::Object(fields)));
        }
        Ok(None)
    }

    fn expand(&self, schema: &Value, depth: usize) -> Result<Value> {
        if depth > 8 {
            return Ok(schema.clone());
        }
        let schema = self.resolve(schema)?;
        Ok(match schema {
            Value::Object(fields) => {
                let mut result = serde_json::Map::new();
                for (name, value) in fields {
                    result.insert(name.clone(), self.expand(value, depth + 1)?);
                }
                Value::Object(result)
            }
            Value::Array(values) => Value::Array(
                values
                    .iter()
                    .map(|value| self.expand(value, depth + 1))
                    .collect::<Result<_>>()?,
            ),
            value => value.clone(),
        })
    }

    fn resolve<'b>(&'b self, mut value: &'b Value) -> Result<&'b Value> {
        for _ in 0..32 {
            let Some(reference) = value.get("$ref").and_then(Value::as_str) else {
                return Ok(value);
            };
            let pointer = reference
                .strip_prefix('#')
                .context("API docs require local OpenAPI references")?;
            value = self
                .document
                .pointer(pointer)
                .with_context(|| format!("missing OpenAPI reference {reference}"))?;
        }
        bail!("cyclic OpenAPI reference")
    }

    fn page_path(route: &str, method: &str) -> Result<String> {
        ensure!(
            route.starts_with('/'),
            "API route must start with /: {route}"
        );
        let route = route
            .strip_prefix("/api/")
            .or_else(|| (route == "/api").then_some(""))
            .unwrap_or_else(|| &route[1..]);
        let mut segments = Vec::new();
        if !route.is_empty() {
            for segment in route.split('/') {
                let segment = if let Some(parameter) = segment
                    .strip_prefix('{')
                    .and_then(|value| value.strip_suffix('}'))
                {
                    format!("_{parameter}")
                } else {
                    segment.to_owned()
                };
                ensure!(
                    !segment.is_empty()
                        && segment != "."
                        && segment != ".."
                        && segment
                            .bytes()
                            .all(|byte| byte.is_ascii_alphanumeric() || b"_-.".contains(&byte)),
                    "unsupported API path segment {segment:?}"
                );
                segments.push(segment);
            }
        }
        segments.push(format!("{method}.md"));
        Ok(segments.join("/"))
    }

    fn header(title: &str, available: bool) -> String {
        format!(
            "---\ntitle: {}\navailable: {available}\n---\n\n{MARKER}\n\n",
            serde_json::to_string(title).expect("string serialization cannot fail")
        )
    }

    fn text<'b>(value: &'b Value, key: &str) -> &'b str {
        value[key].as_str().unwrap_or("")
    }
    fn cell(value: &str) -> String {
        value.replace('|', "\\|").replace(['\r', '\n'], " ")
    }
    fn shell_quote(value: &str) -> String {
        format!("'{}'", value.replace('\'', "'\\''"))
    }
    fn is_generated(value: &str) -> bool {
        value.lines().take(8).any(|line| line == MARKER)
    }

    fn collect_files(directory: &Path, files: &mut Vec<std::path::PathBuf>) -> Result<()> {
        ensure!(
            !directory.is_symlink(),
            "documentation output cannot contain symbolic links"
        );
        if !directory.exists() {
            return Ok(());
        }
        for entry in fs::read_dir(directory)? {
            let path = entry?.path();
            ensure!(
                !path.is_symlink(),
                "documentation output cannot contain symbolic links"
            );
            if path.is_dir() {
                Self::collect_files(&path, files)?;
            } else {
                files.push(path);
            }
        }
        Ok(())
    }
}
